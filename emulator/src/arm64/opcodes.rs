#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Instr {
    pub op: Opcode,
    pub rd: u8,
    pub rn: u8,
    pub rm: u8,
    pub imm: u64,
    pub sf: bool,
    pub cond: u8,
    pub size: u8, // access size in bytes for LDR/STR (0=unused)
}

impl Instr {
    pub const fn nop() -> Self {
        Self {
            op: Opcode::Nop,
            rd: 0,
            rn: 0,
            rm: 0,
            imm: 0,
            sf: true,
            cond: 0,
            size: 0,
        }
    }
}
